import { webkit } from 'playwright';
const out = 'D:/ed-sync/Projects/personal/sites/portfolio/public/sites/';
const b = await webkit.launch();
const p = await (await b.newContext({ viewport: { width: 1440, height: 740 }, deviceScaleFactor: 2 })).newPage();
await p.goto('http://localhost:3000/', { waitUntil: 'networkidle' });
await p.screenshot({ path: out + 'foldready.png' });
const h = await p.evaluate(() => document.documentElement.scrollHeight);
if (h > 740) await p.screenshot({ path: out + 'foldready-full.png', fullPage: true });
console.log('page height', h);
await b.close();
